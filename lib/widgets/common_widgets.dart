class StatusChip extends StatelessWidget {
  const StatusChip({
    super.key,
    required this.label,
    required this.color,
  });

  final String label;
  final Color color;

  factory StatusChip.site(SiteStatus status) {
    switch (status) {
      case SiteStatus.active:
        return const StatusChip(label: 'Active', color: AppColors.teal);
      case SiteStatus.completed:
        return const StatusChip(label: 'Completed', color: AppColors.blue);
      case SiteStatus.onHold:
        return const StatusChip(label: 'On Hold', color: AppColors.coral);
    }
  }

  factory StatusChip.request(MaterialRequestStatus status) {
    switch (status) {
      case MaterialRequestStatus.pending:
        return const StatusChip(label: 'Pending', color: AppColors.slate);
      case MaterialRequestStatus.awaitingResponse:
        return const StatusChip(label: 'Awaiting Response', color: AppColors.safety);
      case MaterialRequestStatus.responseReceived:
        return const StatusChip(label: 'Response Received', color: AppColors.blue);
      case MaterialRequestStatus.approved:
        return const StatusChip(label: 'Approved', color: AppColors.teal);
      case MaterialRequestStatus.rejected:
        return const StatusChip(label: 'Rejected', color: AppColors.coral);
      case MaterialRequestStatus.completed:
        return const StatusChip(label: 'Completed', color: AppColors.teal);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 5),
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.12),
        borderRadius: BorderRadius.circular(8),
      ),
      child: Text(
        label,
        style: TextStyle(
          color: color,
          fontSize: 12,
          fontWeight: FontWeight.w700,
        ),
      ),
    );
  }
}

